    public static bool 업무확정근거인가(string 이름)
        => 전체.Any(x => string.Equals(x.이름, 이름, StringComparison.Ordinal) && x.업무확정근거);

    public static bool 재구성가능한실행인덱스인가(string 이름)
        => 전체.Any(x =>
            string.Equals(x.이름, 이름, StringComparison.Ordinal)
            && x.역할 == 배차상태저장소역할.실행인덱스
            && x.서버재시작후재구성가능);
